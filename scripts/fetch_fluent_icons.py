def fetch(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'myskills-icon-builder'})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def main():
    if not shutil.which('sips'):
        sys.exit('This builder uses macOS sips to resize images.')
    paths = {item['path'] for item in json.loads(fetch(TREE))['tree']}
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    index = []
    with tempfile.TemporaryDirectory() as temp:
        for name, extra in ICONS.items():
            slug = name.lower().replace(' ', '_')
            candidates = [f'assets/{name}/3D/{slug}_3d.png', f'assets/{name}/Default/3D/{slug}_3d_default.png']
            source = next((path for path in candidates if path in paths), None)
            if not source:
                sys.exit(f'Missing 3D image for {name}')
            meta = json.loads(fetch(RAW + urllib.parse.quote(f'assets/{name}/metadata.json')))
            raw = Path(temp) / 'raw.png'
            raw.write_bytes(fetch(RAW + urllib.parse.quote(source)))
            target = OUT / f'{slug}.png'
            subprocess.run(['sips', '-Z', str(SIZE), str(raw), '--out', str(target)], check=True, capture_output=True)
            index.append({'file': target.name, 'name': name, 'glyph': meta.get('glyph', ''),
                          'keywords': sorted(set(meta.get('keywords', []))), 'tags': extra.split()})
            print(name)
    (OUT / 'index.json').write_text(json.dumps({
        'source': 'https://github.com/microsoft/fluentui-emoji',
        'license': 'MIT', 'author': 'Microsoft', 'icons': index}, indent=1, ensure_ascii=False) + '\n')
    (OUT / 'LICENSE').write_bytes(fetch(RAW + 'LICENSE'))


if __name__ == '__main__':
    main()
